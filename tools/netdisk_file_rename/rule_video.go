package main

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"path"
	"regexp"
	"strconv"
	"time"
)

const (
	randomHexIDLength       = 12
	randomHexIDSourceLength = 24
	videoTimeZone           = "Asia/Shanghai"
)

var (
	cloudRecordPattern        = regexp.MustCompile(`^cloudrecord_([0-9a-fA-F]{32})_([0-9]{10}|[0-9]{13})-([0-9a-fA-F]{32})_([0-9]{10}|[0-9]{13})\.mp4$`)
	cloudVideoPattern         = regexp.MustCompile(`^([0-9]{4}-[0-9]{2}-[0-9]{2}_[0-9]{6})_cloud_video\.mp4$`)
	timestampHashPattern      = regexp.MustCompile(`^([0-9]{10}|[0-9]{13})-([0-9a-fA-F]{32})\.mp4$`)
	livePattern               = regexp.MustCompile(`^live_([0-9a-fA-F]{32})_([0-9]{10}|[0-9]{13})\.mp4$`)
	expectedTargetNamePattern = regexp.MustCompile(`^([0-9]{8}_[0-9]{6})_([0-9]{3})_([0-9a-f]{12})(\.[A-Za-z0-9]+)$`)
)

// videoTimestampRule converts a video start time to a stable target name and
// appends a random ID. The ID prevents same-millisecond recordings from
// colliding while BuildPlan still rejects any accidental duplicate.
type videoTimestampRule struct {
	name           string
	pattern        *regexp.Regexp
	timestampGroup int
	parseStart     func(string) (time.Time, error)
	location       *time.Location
	newID          func() (string, error)
}

func newVideoTimestampRule(name string, pattern *regexp.Regexp, timestampGroup int, parseStart func(string) (time.Time, error)) RenameRule {
	return &videoTimestampRule{
		name:           name,
		pattern:        pattern,
		timestampGroup: timestampGroup,
		parseStart:     parseStart,
		// Use a fixed UTC+8 zone so preview and execution do not depend on the
		// host's local timezone or the presence of system timezone data.
		location: time.FixedZone(videoTimeZone, 8*60*60),
		newID:    generateRandomHexID,
	}
}

func (rule *videoTimestampRule) Match(fileName string) bool {
	return rule.pattern.MatchString(fileName)
}

func (rule *videoTimestampRule) IsExpectedName(fileName string) bool {
	return isExpectedTargetName(fileName)
}

func (rule *videoTimestampRule) Rename(fileName string) (string, error) {
	matches := rule.pattern.FindStringSubmatch(fileName)
	if matches == nil || rule.timestampGroup >= len(matches) {
		return "", fmt.Errorf("文件名不符合 %s 规则: %q", rule.name, fileName)
	}
	startTime, err := rule.parseStart(matches[rule.timestampGroup])
	if err != nil {
		return "", fmt.Errorf("解析视频开始时间失败: %w", err)
	}
	extension := path.Ext(fileName)
	if extension == "" {
		return "", fmt.Errorf("文件 %q 没有可保留的扩展名", fileName)
	}
	identifier, err := rule.newID()
	if err != nil {
		return "", fmt.Errorf("生成随机 ID 失败: %w", err)
	}
	localTime := startTime.In(rule.location)
	return fmt.Sprintf("%s_%03d_%s%s",
		localTime.Format("20060102_150405"),
		localTime.Nanosecond()/int(time.Millisecond),
		identifier,
		extension,
	), nil
}

func (rule *videoTimestampRule) Fingerprint() string {
	return fmt.Sprintf("%s/v3;start=%s;layout=YYYYMMDD_HHmmss_SSS;timezone=%s;random=hex%d;extension=preserved",
		rule.name, rule.pattern.String(), videoTimeZone, randomHexIDLength)
}

func parseUnixVideoTimestamp(raw string) (time.Time, error) {
	timestamp, err := strconv.ParseInt(raw, 10, 64)
	if err != nil {
		return time.Time{}, fmt.Errorf("时间戳不是有效整数: %w", err)
	}
	switch len(raw) {
	case 10:
		return time.Unix(timestamp, 0), nil
	case 13:
		return time.UnixMilli(timestamp), nil
	default:
		return time.Time{}, fmt.Errorf("时间戳必须为 10 位秒级或 13 位毫秒级")
	}
}

func parseCloudVideoTime(raw string) (time.Time, error) {
	parsed, err := time.ParseInLocation("2006-01-02_150405", raw, time.FixedZone(videoTimeZone, 8*60*60))
	if err != nil {
		return time.Time{}, fmt.Errorf("日期时间格式必须为 2006-01-02_150405: %w", err)
	}
	return parsed, nil
}

// isExpectedTargetName reports whether a file already has the final naming
// format generated by these rules. Such files are skipped instead of being
// treated as unmatched or renamed again.
func isExpectedTargetName(fileName string) bool {
	matches := expectedTargetNamePattern.FindStringSubmatch(fileName)
	if matches == nil {
		return false
	}
	_, err := time.ParseInLocation("20060102_150405", matches[1], time.FixedZone(videoTimeZone, 8*60*60))
	return err == nil
}

func newCloudRecordRule() RenameRule {
	return newVideoTimestampRule("cloudrecord", cloudRecordPattern, 2, parseUnixVideoTimestamp)
}

func newCloudVideoRule() RenameRule {
	return newVideoTimestampRule("cloud-video", cloudVideoPattern, 1, parseCloudVideoTime)
}

func newTimestampHashRule() RenameRule {
	return newVideoTimestampRule("timestamp-hash", timestampHashPattern, 1, parseUnixVideoTimestamp)
}

func newLiveRule() RenameRule {
	return newVideoTimestampRule("live", livePattern, 2, parseUnixVideoTimestamp)
}

// generateRandomHexID mirrors the supplied JavaScript
// id().slice(0, 12): it first produces 24 lowercase hexadecimal characters,
// then keeps the first 12. It uses crypto/rand instead of Math.random so the
// ID is not predictable.
func generateRandomHexID() (string, error) {
	randomBytes := make([]byte, randomHexIDSourceLength/2)
	if _, err := rand.Read(randomBytes); err != nil {
		return "", err
	}
	return hex.EncodeToString(randomBytes)[:randomHexIDLength], nil
}
